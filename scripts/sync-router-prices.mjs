#!/usr/bin/env node
/**
 * Generate src/pricing/router-prices.generated.ts from the Router's price catalog, the one source
 * of model prices: tangle-router `pricing/researched-provider-prices.json`. Runtime prices tokens
 * no provider billed (a subscription seat, a harness that reports no cost) from this copy and from
 * nothing else, so a run's API-equivalent cost and the Router's charge for the same tokens agree.
 *
 *   node scripts/sync-router-prices.mjs --router <tangle-router checkout> [--ref origin/main] [--check]
 *
 * `--check` fails when the committed copy differs from the catalog at that ref.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const CATALOG = 'pricing/researched-provider-prices.json'
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TARGET = join(ROOT, 'src', 'pricing', 'router-prices.generated.ts')

// The repository's own formatter, so the copy passes `biome check` exactly as written.
const formatted = (text) => execFileSync(join(ROOT, 'node_modules', '.bin', 'biome'), ['format', `--stdin-file-path=${TARGET}`], { cwd: ROOT, input: text, encoding: 'utf8' })

const rate = (value) => (typeof value === 'number' && Number.isFinite(value) && value >= 0 ? value : null)

/**
 * One price per model id. A row states its rates directly or under `policy` (the rates the Router
 * bills by); a `free` row prices at zero. Where two providers list the same id, the provider's own
 * published price wins, then the most recent. Request-size tiers (`policy.tiers`) depend on each
 * request's prompt, which a run total does not keep, so the base rates are used.
 */
export function routerPrices(rows) {
  const chosen = new Map()
  for (const row of rows) {
    if (typeof row?.modelId !== 'string' || row.modelId.length === 0) continue
    const source = row.policy ?? row
    const free = row.status === 'free'
    const input = free ? 0 : rate(source.inputPerToken)
    const output = free ? 0 : rate(source.outputPerToken)
    if (input === null || output === null) continue
    const price = {
      provider: row.provider,
      input,
      cachedInput: free ? 0 : rate(source.cachedInputPerToken),
      cacheWrite: free ? 0 : rate(source.cacheWriteInputPerToken),
      output,
      effectiveFrom: row.effectiveFrom ?? null,
      official: row.authority === 'provider_official',
    }
    const prior = chosen.get(row.modelId)
    const better = prior === undefined ||
      (price.official && !prior.official) ||
      (price.official === prior.official && String(price.effectiveFrom) > String(prior.effectiveFrom))
    if (better) chosen.set(row.modelId, price)
  }
  return Object.fromEntries([...chosen.entries()].sort(([a], [b]) => a.localeCompare(b))
    .map(([id, { official: _official, effectiveFrom: _from, ...price }]) => [id, price]))
}

export function render(prices, source) {
  return `// Generated by scripts/sync-router-prices.mjs from ${source.repository} ${source.path} at ${source.commit}.
// Do not edit: run the script against the Router to change a price. USD per token.
import type { RouterTokenPrice } from './router-prices'

/** The Router catalog file and commit these prices were copied from. */
export const ROUTER_PRICE_SOURCE = ${JSON.stringify(source)} as const

/** USD per token for each model id the Router prices. */
export const ROUTER_TOKEN_PRICES: Readonly<Record<string, RouterTokenPrice>> = ${JSON.stringify(prices, null, 2)}
`
}

function main(argv) {
  const value = (name, fallback) => { const index = argv.indexOf(name); return index >= 0 ? argv[index + 1] : fallback }
  const router = value('--router', process.env.TANGLE_ROUTER_DIR)
  if (!router) throw new Error('usage: sync-router-prices.mjs --router <tangle-router checkout> [--ref origin/main] [--check]')
  const ref = value('--ref', 'origin/main')
  const git = (...args) => execFileSync('git', ['-C', resolve(router), ...args], { encoding: 'utf8', maxBuffer: 64 << 20 })
  const commit = git('rev-parse', ref).trim()
  const rows = JSON.parse(git('show', `${commit}:${CATALOG}`))
  const prices = routerPrices(rows)
  const text = formatted(render(prices, { repository: 'tangle-network/tangle-router', path: CATALOG, commit }))
  if (argv.includes('--check')) {
    const current = readFileSync(TARGET, 'utf8')
    if (current !== text) {
      process.stderr.write(`${TARGET} differs from ${CATALOG} at ${commit}; run scripts/sync-router-prices.mjs --router ${router}\n`)
      process.exitCode = 1
    }
    return
  }
  writeFileSync(TARGET, text)
  process.stdout.write(`wrote ${Object.keys(prices).length} model prices from ${commit}\n`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2))
